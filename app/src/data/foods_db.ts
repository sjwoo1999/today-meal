// Helper function to search foods
export function searchFoods(query: string): FoodDBItem[] {
    const lowerQuery = query.toLowerCase();
    return foodsDB.filter(food =>
        food.nameKr.includes(query) ||
        food.name.toLowerCase().includes(lowerQuery) ||
        food.tags.some(tag => tag.includes(query))
    );
}

// Helper function to get food by ID
export function getFoodById(id: string): FoodDBItem | undefined {
    return foodsDB.find(food => food.id === id);
}

// Helper function to get popular foods
export function getPopularFoods(limit: number = 10): FoodDBItem[] {
    return [...foodsDB]
        .sort((a, b) => b.popularityScore - a.popularityScore)
        .slice(0, limit);
}

// Helper function to get foods by category
export function getFoodsByCategory(category: FoodDBItem['category']): FoodDBItem[] {
    return foodsDB.filter(food => food.category === category);
}

// Mock AI recognition - returns a random food weighted by popularity with confidence
export function mockRecognizeFood(): { food: FoodDBItem; confidence: number } {
    const popularFoods = foodsDB.filter(f => f.popularityScore >= 85);
    const food = popularFoods[Math.floor(Math.random() * popularFoods.length)];
    // Random confidence between 0.75 and 0.98
    const confidence = 0.75 + Math.random() * 0.23;
    return { food, confidence };
}
